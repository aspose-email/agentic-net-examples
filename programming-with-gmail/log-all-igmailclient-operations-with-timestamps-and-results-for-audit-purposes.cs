using System;
using System.Collections.Generic;
using Aspose.Email;
using Aspose.Email.Clients.Google;

namespace GmailAuditSample
{
    class Program
    {
        static void Main(string[] args)
        {
            try
            {
                // Placeholder credentials – replace with real values.
                string accessToken = "YOUR_ACCESS_TOKEN";
                string defaultEmail = "user@example.com";

                // Skip execution if placeholder credentials are detected.
                if (string.IsNullOrWhiteSpace(accessToken) || accessToken == "YOUR_ACCESS_TOKEN")
                {
                    Console.Error.WriteLine("Access token not provided. Skipping Gmail operations.");
                    return;
                }

                // Create the Gmail client and ensure it is disposed properly.
                using (IGmailClient gmailClient = GmailClient.GetInstance(accessToken, defaultEmail))
                {
                    // ------------------------------------------------------------
                    // 1. List messages in the mailbox.
                    // ------------------------------------------------------------
                    List<GmailMessageInfo> messageInfos = null;
                    try
                    {
                        messageInfos = gmailClient.ListMessages();
                        Console.WriteLine($"{DateTime.UtcNow:u} - ListMessages succeeded. Count: {messageInfos.Count}");
                    }
                    catch (Exception ex)
                    {
                        Console.Error.WriteLine($"{DateTime.UtcNow:u} - ListMessages failed: {ex.Message}");
                    }

                    // ------------------------------------------------------------
                    // 2. Fetch the first message (if any) and display its subject.
                    // ------------------------------------------------------------
                    if (messageInfos != null && messageInfos.Count > 0)
                    {
                        string firstMessageId = messageInfos[0].Id;
                        try
                        {
                            MailMessage fetchedMessage = gmailClient.FetchMessage(firstMessageId);
                            Console.WriteLine($"{DateTime.UtcNow:u} - FetchMessage succeeded. Subject: {fetchedMessage.Subject}");
                            fetchedMessage.Dispose();
                        }
                        catch (Exception ex)
                        {
                            Console.Error.WriteLine($"{DateTime.UtcNow:u} - FetchMessage failed: {ex.Message}");
                        }
                    }

                    // ------------------------------------------------------------
                    // 3. Send a test email.
                    // ------------------------------------------------------------
                    MailMessage testMessage = null;
                    try
                    {
                        testMessage = new MailMessage();
                        testMessage.From = defaultEmail;
                        testMessage.To.Add(defaultEmail);
                        testMessage.Subject = "Test email from Aspose Gmail client";
                        testMessage.Body = "This is a test email generated by the audit sample.";
                        string sentMessageId = gmailClient.SendMessage(testMessage);
                        Console.WriteLine($"{DateTime.UtcNow:u} - SendMessage succeeded. Id: {sentMessageId}");
                    }
                    catch (Exception ex)
                    {
                        Console.Error.WriteLine($"{DateTime.UtcNow:u} - SendMessage failed: {ex.Message}");
                    }
                    finally
                    {
                        if (testMessage != null)
                        {
                            testMessage.Dispose();
                        }
                    }

                    // ------------------------------------------------------------
                    // 4. List message filters.
                    // ------------------------------------------------------------
                    try
                    {
                        List<Filter> filters = gmailClient.ListFilters();
                        Console.WriteLine($"{DateTime.UtcNow:u} - ListFilters succeeded. Count: {filters.Count}");
                    }
                    catch (Exception ex)
                    {
                        Console.Error.WriteLine($"{DateTime.UtcNow:u} - ListFilters failed: {ex.Message}");
                    }

                    // ------------------------------------------------------------
                    // 5. Delete the first message (if any) to demonstrate delete logging.
                    // ------------------------------------------------------------
                    if (messageInfos != null && messageInfos.Count > 0)
                    {
                        string deleteMessageId = messageInfos[0].Id;
                        try
                        {
                            gmailClient.DeleteMessage(deleteMessageId);
                            Console.WriteLine($"{DateTime.UtcNow:u} - DeleteMessage succeeded. Id: {deleteMessageId}");
                        }
                        catch (Exception ex)
                        {
                            Console.Error.WriteLine($"{DateTime.UtcNow:u} - DeleteMessage failed: {ex.Message}");
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine($"Unhandled exception: {ex.Message}");
            }
        }
    }
}
